// Discount percent off the usual price, rounded to a whole number.
// Negative when the sale price sits above the usual price (an inflated "deal").
export function discountPct(d) {
  return Math.round(((d.usual - d.sale) / d.usual) * 100);
}

export function dollarsSaved(d) {
  return Math.round((d.usual - d.sale) * 100) / 100;
}

export function money(n) {
  return '$' + n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}
